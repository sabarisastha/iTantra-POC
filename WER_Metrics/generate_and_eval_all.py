def save_wav_16k(samples, sample_rate, filepath):
    if sample_rate != 16000:
        num_output_samples = int(len(samples) * 16000 / sample_rate)
        samples = scipy.signal.resample(samples, num_output_samples)
    
    samples_int16 = (samples * 32767.0).clip(-32768, 32767).astype(np.int16)
    with wave.open(filepath, "wb") as f:
        f.setnchannels(1)
        f.setsampwidth(2)
        f.setframerate(16000)
        f.writeframes(samples_int16.tobytes())

